import React, { useState, useEffect } from 'react';
import { View, Text, TextInput, StyleSheet, Button, ScrollView, Alert, TouchableOpacity, Modal } from 'react-native';
import { useLocalSearchParams, useRouter } from 'expo-router';
import { CameraView, useCameraPermissions } from 'expo-camera';
import Ionicons from '@expo/vector-icons/Ionicons';
import { useLanguage } from '../context/LanguageContext';
import { useHistory } from '../context/HistoryContext';
import { useAuth } from '../context/AuthContext';

export default function EditScreen() {
  const { i18n } = useLanguage();
  const router = useRouter();
  const params = useLocalSearchParams();
  const { addToHistory } = useHistory();
  const { user } = useAuth();
  const [permission, requestPermission] = useCameraPermissions();

  const [itemName, setItemName] = useState('');
  const [itemCode, setItemCode] = useState('');
  const [ocrText, setOcrText] = useState('');
  const [isSaving, setIsSaving] = useState(false);
  const [isScanning, setIsScanning] = useState(false);

  useEffect(() => {
    if (params.ocrText) {
      setOcrText(params.ocrText);
    }
  }, [params.ocrText]);

  useEffect(() => {
    // Generate 13-digit code
    const generatedCode = generate13DigitCode();
    setItemCode(generatedCode);
  }, []);

  const generate13DigitCode = () => {
    // Simple generation: timestamp + random to make 13 digits
    // Date.now() is 13 digits usually, but let's be safe
    const timestamp = Date.now().toString();
    const random = Math.floor(Math.random() * 1000).toString();
    return (timestamp + random).slice(0, 13);
  };

  const handleBarcodeScanned = ({ data }) => {
    setItemCode(data);
    setIsScanning(false);
  };

  const startScanning = async () => {
    if (!permission?.granted) {
      const { status } = await requestPermission();
      if (status !== 'granted') {
        Alert.alert(i18n.permissionNeeded, i18n.cameraPermissionBarcode);
        return;
      }
    }
    setIsScanning(true);
  };

  const handleSave = async () => {
    if (!itemName.trim()) {
      Alert.alert(i18n.error, i18n.enterItemName);
      return;
    }

    setIsSaving(true);
    try {
      // Save to backend
      // Use your computer's local IP address instead of localhost/10.0.2.2 for physical devices
      const response = await fetch('http://192.168.50.124:3000/api/SaveScanHistory', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
        },
        body: JSON.stringify({
          itemName: itemName,
          itemCode: itemCode,
          nutritionInformation: ocrText,
          userId: user ? user.userId : 'anonymous'
        }),
      });

      if (response.ok) {
        // Also add to local history context for immediate display
        addToHistory({
          itemName: itemName,
          itemCode: itemCode,
          nutritionInformation: ocrText
        });
        
        Alert.alert(i18n.success, i18n.saveSuccess, [
          { 
            text: 'OK', 
            onPress: () => router.push({
              pathname: '/product-details',
              params: { 
                itemName: itemName, 
                itemCode: itemCode, 
                nutritionInformation: ocrText 
              }
            }) 
          }
        ]);
      } else {
        Alert.alert(i18n.error, i18n.saveError);
      }
    } catch (error) {
      console.error(error);
      Alert.alert(i18n.error, i18n.connectError);
    } finally {
      setIsSaving(false);
    }
  };

  return (
    <ScrollView contentContainerStyle={styles.container}>
      <Text style={styles.title}>{i18n.editScan}</Text>

      <View style={styles.inputGroup}>
        <Text style={styles.label}>{i18n.itemName}</Text>
        <TextInput
          style={styles.input}
          value={itemName}
          onChangeText={setItemName}
          placeholder={i18n.itemName}
        />
      </View>

      <View style={styles.inputGroup}>
        <Text style={styles.label}>{i18n.itemCode}</Text>
        <View style={styles.codeContainer}>
          <TextInput
            style={[styles.input, styles.disabledInput, { flex: 1 }]}
            value={itemCode}
            editable={false}
          />
          <TouchableOpacity style={styles.scanButton} onPress={startScanning}>
            <Ionicons name="barcode-outline" size={24} color="white" />
          </TouchableOpacity>
        </View>
        <Text style={styles.helperText}>{i18n.autoGeneratedHelper}</Text>
      </View>

      <View style={styles.inputGroup}>
        <Text style={styles.label}>{i18n.ocrResult}</Text>
        <TextInput
          style={[styles.input, styles.textArea]}
          value={ocrText}
          onChangeText={setOcrText}
          multiline
          numberOfLines={10}
          textAlignVertical="top"
        />
      </View>

      <View style={styles.buttonContainer}>
        <TouchableOpacity 
          style={[styles.button, styles.returnButton]} 
          onPress={() => router.push('/scan')}
        >
          <Text style={styles.buttonText}>{i18n.return}</Text>
        </TouchableOpacity>

        <TouchableOpacity 
          style={[styles.button, styles.saveButton]} 
          onPress={handleSave}
          disabled={isSaving}
        >
          <Text style={styles.buttonText}>{isSaving ? i18n.saving : i18n.save}</Text>
        </TouchableOpacity>
      </View>

      <Modal visible={isScanning} animationType="slide">
        <View style={styles.cameraContainer}>
          <CameraView
            style={styles.camera}
            onBarcodeScanned={handleBarcodeScanned}
            barcodeScannerSettings={{
              barcodeTypes: ["qr", "ean13", "upc_e"],
            }}
          >
            <View style={styles.cameraOverlay}>
              <Text style={styles.cameraText}>{i18n.scanBarcode}</Text>
              <TouchableOpacity style={styles.closeButton} onPress={() => setIsScanning(false)}>
                <Text style={styles.closeButtonText}>{i18n.cancel}</Text>
              </TouchableOpacity>
            </View>
          </CameraView>
        </View>
      </Modal>
    </ScrollView>
  );
}

